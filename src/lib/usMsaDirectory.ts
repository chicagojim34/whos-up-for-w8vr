/**
 * Calculates the great-circle distance between two geographic points in miles using the Haversine formula.
 */
export function calculateDistanceMiles(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  if (lat1 === lat2 && lon1 === lon2) return 0;
  const R = 3958.8; // Earth's radius in miles
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) *
      Math.cos(lat2 * (Math.PI / 180)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

/**
 * Resolves geographic coordinates for a given city, suburb, or venue address.
 */
export function resolveCityCoordinates(
  cityOrAddress?: string
): { lat: number; lng: number } | undefined {
  if (!cityOrAddress || !cityOrAddress.trim()) return undefined;

  const clean = cityOrAddress.trim().toLowerCase().replace(/[^a-z0-9,\s]/g, ' ').replace(/\s+/g, ' ');

  // 1. Direct match in METRO_COORDINATES
  if (METRO_COORDINATES[clean]) {
    return { lat: METRO_COORDINATES[clean].lat, lng: METRO_COORDINATES[clean].lng };
  }

  // 2. Match city prefix (e.g., "Naperville, IL 60540" -> "naperville, il")
  for (const [key, coords] of Object.entries(METRO_COORDINATES)) {
    if (clean.includes(key) || key.includes(clean)) {
      return { lat: coords.lat, lng: coords.lng };
    }
  }

  // 3. Fallback to MSA lookup
  const msa = findMsaByCity(cityOrAddress);
  if (msa) {
    const msaKey = msa.primaryCity.toLowerCase();
    if (METRO_COORDINATES[msaKey]) {
      return { lat: METRO_COORDINATES[msaKey].lat, lng: METRO_COORDINATES[msaKey].lng };
    }
  }

  return undefined;
}

export interface MetroMarketInfo {
  msa: MetropolitanStatisticalArea;
  metroLabel: string;
  isSuburb: boolean;
  primaryCity: string;
  suburbName?: string;
  distanceToCentroidMiles?: number;
}

/**
 * Returns parent Metro Market information for any city, town, or suburb.
 * (e.g., "Naperville" -> returns Chicago-Naperville-Elgin MSA, isSuburb: true, metroLabel: "Chicago Metro Area", distance: ~28 mi)
 */
export function getMetroMarketForCity(cityOrTown: string): MetroMarketInfo | undefined {
  if (!cityOrTown || !cityOrTown.trim()) return undefined;
  const clean = cityOrTown.trim().toLowerCase().replace(/[^a-z0-9,\s]/g, ' ').replace(/\s+/g, ' ');

  const coordEntry = METRO_COORDINATES[clean] || 
    Object.entries(METRO_COORDINATES).find(([k]) => clean.includes(k))?.[1];

  let msa: MetropolitanStatisticalArea | undefined;
  if (coordEntry?.msaCode) {
    msa = findMsaByCode(coordEntry.msaCode);
  }
  if (!msa) {
    msa = findMsaByCity(cityOrTown);
  }
  if (!msa) return undefined;

  const isPrimary = msa.primaryCity.toLowerCase() === clean || clean.startsWith(msa.primaryCity.toLowerCase());
  const metroLabel = coordEntry?.parentMetro || `${msa.primaryCity} Metro Area`;

  let distanceToCentroidMiles: number | undefined;
  const centerCoords = METRO_COORDINATES[msa.primaryCity.toLowerCase()];
  if (coordEntry && centerCoords) {
    distanceToCentroidMiles = calculateDistanceMiles(
      centerCoords.lat,
      centerCoords.lng,
      coordEntry.lat,
      coordEntry.lng
    );
  }

  return {
    msa,
    metroLabel,
    isSuburb: !isPrimary,
    primaryCity: msa.primaryCity,
    suburbName: !isPrimary ? cityOrTown.split(',')[0].trim() : undefined,
    distanceToCentroidMiles,
  };
}

/**
 * Finds the nearest MSA among known metropolitan centers for given GPS coordinates.
 */
export function findNearestMsa(
  lat: number,
  lng: number
): { msa: MetropolitanStatisticalArea; distanceMiles: number; metroLabel: string } {
  let nearestMsa = US_387_METROPOLITAN_AREAS[0]; // fallback
  let minDistance = Infinity;
  let label = 'US Metro';

  for (const [, coords] of Object.entries(METRO_COORDINATES)) {
    if (!coords.msaCode) continue;
    const dist = calculateDistanceMiles(lat, lng, coords.lat, coords.lng);
    if (dist < minDistance) {
      minDistance = dist;
      const m = findMsaByCode(coords.msaCode);
      if (m) {
        nearestMsa = m;
        label = coords.parentMetro || `${m.primaryCity} Metro Area`;
      }
    }
  }

  return {
    msa: nearestMsa,
    distanceMiles: minDistance,
    metroLabel: label,
  };
}

