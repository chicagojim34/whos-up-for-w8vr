/**
 * Fuzzy search across all 387 Metropolitan Statistical Areas
 */
export function searchMsas(query: string): MetropolitanStatisticalArea[] {
  if (!query || !query.trim()) return [...ALPHABETICAL_387_MSAS];

  const q = query.trim().toLowerCase();
  const qTokens = q.split(/\s+/).filter(Boolean);

  return ALPHABETICAL_387_MSAS.filter(m => {
    const cityLower = m.primaryCity.toLowerCase();
    const titleLower = m.title.toLowerCase();
    const stateLower = m.primaryState.toLowerCase();

    // Exact city or title match
    if (cityLower === q || titleLower.includes(q)) return true;

    // State code match (e.g. 'MO', 'IL', 'TX')
    if (stateLower === q) return true;

    // Component cities match (e.g. 'Naperville', 'St. Paul', 'Fort Worth')
    if (m.componentCities?.some(c => c.toLowerCase().includes(q))) return true;

    // Multi-token match
    return qTokens.every(tok => 
      cityLower.includes(tok) || 
      titleLower.includes(tok) || 
      stateLower === tok ||
      m.componentCities?.some(c => c.toLowerCase().includes(tok))
    );
  });
}

/**
 * Find exact or nearest MSA for a given city name
 */
export function findMsaByCity(city: string): MetropolitanStatisticalArea | undefined {
  if (!city || !city.trim()) return undefined;
  const c = city.trim().toLowerCase();

  return US_387_METROPOLITAN_AREAS.find(m => {
    if (m.primaryCity.toLowerCase() === c) return true;
    if (m.title.toLowerCase().includes(c)) return true;
    if (m.componentCities?.some(comp => comp.toLowerCase() === c)) return true;
    return false;
  });
}

/**
 * Find MSA by 5-digit CBSA code
 */
export function findMsaByCode(cbsaCode: string): MetropolitanStatisticalArea | undefined {
  return US_387_METROPOLITAN_AREAS.find(m => m.cbsaCode === cbsaCode);
}

